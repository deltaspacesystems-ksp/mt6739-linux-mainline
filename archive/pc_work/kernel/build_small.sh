#!/bin/bash
# Maly kernel 7.3 (allnoconfig + minimum) -> mala paczka boot, zeby zmiescic sie w limitach LK
set -e
K=/home/y5/linux-7.3; S=/mnt/d/y5_linux_work/kernel
cd $K
cp $S/mt6739.dtsi $S/mt6739-huawei-dra.dts arch/arm64/boot/dts/mediatek/
export ARCH=arm64 CROSS_COMPILE=aarch64-linux-gnu-
make allnoconfig >/dev/null
cat >> .config <<'EOF'
CONFIG_64BIT=y
CONFIG_ARCH_MEDIATEK=y
CONFIG_MMU=y
CONFIG_PRINTK=y
CONFIG_PRINTK_TIME=y
CONFIG_BINFMT_ELF=y
CONFIG_BINFMT_SCRIPT=y
CONFIG_BLK_DEV_INITRD=y
CONFIG_RD_GZIP=y
CONFIG_TTY=y
CONFIG_VT=y
CONFIG_VT_CONSOLE=y
CONFIG_FRAMEBUFFER_CONSOLE=y
CONFIG_FONT_SUPPORT=y
CONFIG_FONTS=y
CONFIG_FONT_8x16=y
CONFIG_SERIAL_8250=y
CONFIG_SERIAL_8250_CONSOLE=y
CONFIG_SERIAL_8250_MT6577=y
CONFIG_SERIAL_EARLYCON=y
CONFIG_SYSFB_SIMPLEFB=y
CONFIG_DRM=y
CONFIG_DRM_SIMPLEDRM=y
CONFIG_DRM_FBDEV_EMULATION=y
CONFIG_FB=y
CONFIG_FB_SIMPLE=y
CONFIG_MISC_FILESYSTEMS=y
CONFIG_PSTORE=y
CONFIG_PSTORE_CONSOLE=y
CONFIG_PSTORE_RAM=y
CONFIG_WATCHDOG=y
CONFIG_MEDIATEK_WATCHDOG=y
CONFIG_WATCHDOG_HANDLE_BOOT_ENABLED=y
CONFIG_PANIC_TIMEOUT=0
CONFIG_DEVTMPFS=y
CONFIG_DEVTMPFS_MOUNT=y
CONFIG_TMPFS=y
CONFIG_PROC_FS=y
CONFIG_SYSFS=y
CONFIG_UNIX=y
CONFIG_NET=y
CONFIG_INET=y
CONFIG_NETDEVICES=y
CONFIG_MMC=y
CONFIG_MMC_BLOCK=y
CONFIG_MMC_MTK=y
CONFIG_EXT4_FS=y
CONFIG_USB_SUPPORT=y
CONFIG_USB=y
CONFIG_USB_MUSB_HDRC=y
CONFIG_USB_MUSB_MEDIATEK=y
CONFIG_USB_MUSB_DUAL_ROLE=y
CONFIG_NOP_USB_XCEIV=y
CONFIG_USB_GADGET=y
CONFIG_USB_CONFIGFS=y
CONFIG_USB_CONFIGFS_RNDIS=y
CONFIG_CONFIGFS_FS=y
CONFIG_SERIO=y
CONFIG_INPUT=y
EOF
make olddefconfig >/dev/null
grep -E 'CONFIG_(ARCH_MEDIATEK|DRM_SIMPLEDRM|FRAMEBUFFER_CONSOLE|PSTORE_RAM|MMC_MTK|USB_MUSB_MEDIATEK|USB_CONFIGFS_RNDIS|BLK_DEV_INITRD)=' .config
make -j8 Image mediatek/mt6739-huawei-dra.dtb 2>&1 | tail -n 5
ls -l arch/arm64/boot/Image arch/arm64/boot/dts/mediatek/mt6739-huawei-dra.dtb
